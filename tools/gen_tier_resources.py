"""Generates the tier resources (blockstates, models, loot tables, recipes, lang, tags) for mekanismgizmo.

Run:  python tools/gen_tier_resources.py
"""
import io
import json
import os

TIERS = ['', 'basic_', 'advanced_', 'elite_', 'ultimate_']
MACHINES = ['potion_brewer', 'ice_maker', 'cobblestone_generator', 'basalt_generator', 'fluid_injector', 'liquid_heater']
# Machines that exist only once, without tiers
SINGLES = ['item_collector', 'wind_fusion', 'machine_resetter', 'improved_gas_generator', 'heat_fusion']
# Machines that use a single model for the block item (no LED composite); empty since every machine carries the
# tier ledge. Kept as a hook for a future machine that wants to do without it.
THREE_D = {}

# Machines whose *body* is a 3D model: the body file is generated by tools/gen_mek_based_models.py and not rewritten here,
# but the block still uses the same tier LED composite around it (so the tier band keeps working).
THREE_D_BODIES = {'potion_brewer', 'ice_maker', 'cobblestone_generator', 'basalt_generator', 'fluid_injector',
                  'liquid_heater', 'item_collector', 'machine_resetter', 'heat_fusion', 'improved_gas_generator',
                  'wind_fusion'}
ASSETS = 'src/main/resources/assets/mekanismgizmo'
DATA = 'src/main/resources/data/mekanismgizmo'
COMPONENTS = ['mekanism:ejector', 'mekanism:owner', 'mekanism:redstone_control', 'mekanism:security',
              'mekanism:side_config', 'mekanism:upgrades', 'mekanism:energy', 'mekanism:items',
              'mekanism:fluids', 'mekanism:chemicals']


def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(json.dumps(obj, indent=2) + '\n')


def names(machine):
    if machine in SINGLES:
        yield '', machine
        return
    for tier in TIERS:
        yield tier, f'{tier}{machine}'


# --- the tier band of Mekanism's factories --------------------------------------------------------
# Mekanism marks a tier with a real ledge on the top front edge of the block: a 6 pixel wide strip whose front face
# runs down the front and whose top face carries the colour over the top of the machine. The strip is one texture with
# a row per tier, so each tier model only samples a different row.
LED_ROWS = {'untiered': 0, 'basic': 1, 'advanced': 2, 'elite': 3, 'ultimate': 4}


def led_model(row):
    return {
        'textures': {'led': 'mekanismgizmo:block/front_led'},
        'elements': [{
            'name': 'front_led',
            'from': [4.98, 15.0, -0.02],
            'to': [11.02, 16.02, 1.0],
            'faces': {
                'north': {'uv': [0, row, 6, row + 1], 'texture': '#led'},
                'up': {'uv': [0, row, 6, row + 1], 'rotation': 180, 'texture': '#led'},
            },
        }],
    }


for key, row in LED_ROWS.items():
    write(f'{ASSETS}/models/block/front_led/{key}.json', led_model(row))


# --- blockstates / models / loot tables -----------------------------------------------------------
for machine in MACHINES + SINGLES:
    for _tier, name in names(machine):
        variants = {}
        for active in ('false', 'true'):
            for facing, y in (('north', None), ('south', 180), ('west', 270), ('east', 90)):
                variant = {'model': 'mekanismgizmo:block/%s' % THREE_D.get(name, name)}
                if y is not None:
                    variant['y'] = y
                variants[f'active={active},facing={facing}'] = variant
        write(f'{ASSETS}/blockstates/{name}.json', {'variants': variants})
        if name in THREE_D:
            # a machine without an LED composite: the model is written by its own generator, only the item points at it
            write(f'{ASSETS}/models/item/{name}.json', {'parent': f'mekanismgizmo:block/{THREE_D[name]}'})
            write(f'{DATA}/loot_table/blocks/{name}.json', {
                'type': 'minecraft:block',
                'pools': [{
                    'bonus_rolls': 0.0,
                    'entries': [{
                        'type': 'minecraft:item',
                        'name': f'mekanismgizmo:{name}',
                        'functions': [
                            {'function': 'minecraft:copy_name', 'source': 'block_entity'},
                            {'function': 'minecraft:copy_components', 'source': 'block_entity', 'include': COMPONENTS},
                        ],
                    }],
                    'name': 'main',
                    'rolls': 1.0,
                }],
                'random_sequence': f'mekanismgizmo:blocks/{name}',
            })
            continue
        if machine not in THREE_D_BODIES:
            write(f'{ASSETS}/models/block/{name}_body.json', {
                'parent': 'minecraft:block/cube',
                'textures': {
                    'particle': f'mekanismgizmo:block/{name}_front',
                    'down': f'mekanismgizmo:block/{name}_bottom',
                    'up': f'mekanismgizmo:block/{name}_top',
                    'north': f'mekanismgizmo:block/{name}_front',
                    'south': f'mekanismgizmo:block/{name}_back',
                    'east': f'mekanismgizmo:block/{name}_side',
                    'west': f'mekanismgizmo:block/{name}_side',
                },
            })
        # The block itself is the body plus the tier LED ledge, the way Mekanism's factories are built. A 3D body needs
        # the cut-out render type on the composite as well, or its transparent parts would be drawn solid.
        composite = {
            'loader': 'neoforge:composite',
            'parent': 'block/block',
            'textures': {'particle': f'mekanismgizmo:block/{name}_front'},
            'children': {
                'base': {'parent': f'mekanismgizmo:block/{name}_body'},
                'front_led': {'parent': f'mekanismgizmo:block/front_led/{_tier.rstrip("_") or "untiered"}'},
            },
        }
        if machine in THREE_D_BODIES:
            composite['render_type'] = 'minecraft:cutout'
        write(f'{ASSETS}/models/block/{name}.json', composite)
        write(f'{ASSETS}/models/item/{name}.json', {'parent': f'mekanismgizmo:block/{name}'})
        write(f'{DATA}/loot_table/blocks/{name}.json', {
            'type': 'minecraft:block',
            'pools': [{
                'bonus_rolls': 0.0,
                'entries': [{
                    'type': 'minecraft:item',
                    'name': f'mekanismgizmo:{name}',
                    'functions': [
                        {'function': 'minecraft:copy_name', 'source': 'block_entity'},
                        {'function': 'minecraft:copy_components', 'source': 'block_entity', 'include': COMPONENTS},
                    ],
                }],
                'name': 'main',
                'rolls': 1.0,
            }],
            'random_sequence': f'mekanismgizmo:blocks/{name}',
        })

# --- upgrade recipes: same shape as Mekanism's factory tier recipes --------------------------------
STEPS = {
    'basic_': {'alloy': 'mekanism:alloys/infused', 'circuit': 'c:circuits/advanced', 'ingot': 'c:ingots/osmium'},
    'advanced_': {'alloy': 'mekanism:alloys/reinforced', 'circuit': 'c:circuits/elite', 'ingot': 'c:ingots/gold'},
    'elite_': {'alloy': 'mekanism:alloys/atomic', 'circuit': 'c:circuits/ultimate', 'ingot': 'c:gems/diamond'},
    'ultimate_': {'alloy': 'mekanism:alloys/atomic', 'circuit': 'c:circuits/ultimate', 'ingot': 'c:gems/diamond'},
}
for machine in MACHINES:
    previous = machine
    for tier in TIERS[1:]:
        name = f'{tier}{machine}'
        step = STEPS[tier]
        write(f'{DATA}/recipe/{name}.json', {
            'type': 'minecraft:crafting_shaped',
            'category': 'misc',
            'key': {
                'A': {'tag': step['alloy']},
                'C': {'tag': step['circuit']},
                'I': {'tag': step['ingot']},
                'P': {'item': f'mekanismgizmo:{previous}'},
            },
            'pattern': ['ACA', 'IPI', 'ACA'],
            'result': {'count': 1, 'id': f'mekanismgizmo:{name}'},
        })
        previous = name

# --- the wind generator fusion machine: wind generators around a steel casing -----------------------
write(f'{DATA}/recipe/wind_fusion.json', {
    'type': 'minecraft:crafting_shaped',
    'category': 'misc',
    'key': {
        'A': {'tag': 'mekanism:alloys/basic'},
        'W': {'item': 'mekanismgenerators:wind_generator'},
        'P': {'item': 'mekanism:steel_casing'},
    },
    'pattern': ['AWA', 'WPW', 'AWA'],
    'result': {'count': 1, 'id': 'mekanismgizmo:wind_fusion'},
})

# --- the machine resetter: circuits and sponges around a steel casing -------------------------------
write(f'{DATA}/recipe/machine_resetter.json', {
    'type': 'minecraft:crafting_shaped',
    'category': 'misc',
    'key': {
        'A': {'tag': 'mekanism:alloys/basic'},
        'C': {'tag': 'c:circuits/basic'},
        'W': {'item': 'minecraft:sponge'},
        'X': {'item': 'mekanism:steel_casing'},
    },
    'pattern': ['ACA', 'WXW', 'ACA'],
    'result': {'count': 1, 'id': 'mekanismgizmo:machine_resetter'},
})

# --- pickaxe tag ----------------------------------------------------------------------------------
values = []
for machine in MACHINES + SINGLES:
    for _tier, name in names(machine):
        values.append(f'mekanismgizmo:{name}')
write('src/main/resources/data/minecraft/tags/block/mineable/pickaxe.json', {'values': values})

# --- lang -----------------------------------------------------------------------------------------
EN_TIER = {'': '', 'basic_': 'Basic ', 'advanced_': 'Advanced ', 'elite_': 'Elite ', 'ultimate_': 'Ultimate '}
JA_TIER = {'': '', 'basic_': '\u57fa\u672c', 'advanced_': '\u767a\u5c55', 'elite_': '\u7cbe\u92ed',
           'ultimate_': '\u7a76\u6975'}
EN_NAMES = {
    'potion_brewer': 'Potion Brewer',
    'ice_maker': 'Ice Maker',
    'cobblestone_generator': 'Electric Cobblestone Generator',
    'basalt_generator': 'Electric Basalt Generator',
    'fluid_injector': 'Fluid Injector',
    'item_collector': 'Item Collector',
    'wind_fusion': 'Wind Generator Fusion',
    'machine_resetter': 'Machine Resetter',
    'liquid_heater': 'Liquid Heater',
    'improved_gas_generator': 'Improved Gas Generator',
    'heat_fusion': 'Heat Generator Fusion',
}
JA_NAMES = {
    'potion_brewer': '\u30dd\u30fc\u30b7\u30e7\u30f3\u91b8\u9020\u6a5f',
    'ice_maker': '\u88fd\u6c37\u6a5f',
    'cobblestone_generator': '\u96fb\u52d5\u4e38\u77f3\u88fd\u9020\u6a5f',
    'basalt_generator': '\u96fb\u52d5\u7384\u6b66\u5ca9\u88fd\u9020\u6a5f',
    'fluid_injector': '\u6d41\u4f53\u6ce8\u5165\u6a5f',
    'item_collector': '\u30a2\u30a4\u30c6\u30e0\u53ce\u96c6\u6a5f',
    'wind_fusion': '\u98a8\u529b\u767a\u96fb\u878d\u5408\u6a5f',
    'machine_resetter': '\u6a5f\u68b0\u30ea\u30bb\u30c3\u30c8\u6a5f',
    'liquid_heater': '\u6db2\u4f53\u52a0\u71b1\u5668',
    'improved_gas_generator': '\u6539\u826f\u578b\u30ac\u30b9\u767a\u96fb\u6a5f',
    'heat_fusion': '\u71b1\u767a\u96fb\u878d\u5408\u6a5f',
}
for lang, tier_names, machine_names in (('en_us', EN_TIER, EN_NAMES), ('ja_jp', JA_TIER, JA_NAMES)):
    path = f'{ASSETS}/lang/{lang}.json'
    data = json.loads(io.open(path, encoding='utf-8').read())
    for machine in MACHINES + SINGLES:
        for tier, name in names(machine):
            title = f'{tier_names[tier]}{machine_names[machine]}' if lang == 'en_us' \
                else f'{tier_names[tier]}{machine_names[machine]}'
            # The GUI title comes from TileEntityMekanism#getDisplayName -> "container.<namespace>.<block path>"
            data[f'container.mekanismgizmo.{name}'] = title
            data[f'block.mekanismgizmo.{name}'] = title
    io.open(path, 'w', encoding='utf-8', newline='\n').write(
        json.dumps(dict(sorted(data.items())), indent=2, ensure_ascii=False) + '\n')

print('tier resources generated')
